/* sysinfo.h - сбор сведений о вычислительной системе */
#ifndef SYSINFO_H
#define SYSINFO_H

typedef struct {
    char cpu_model[128];   /* модель процессора */
    char governor[32];     /* активный режим управления частотой */
    char os_name[128];     /* наименование операционной системы */
    char kernel[96];       /* версия ядра */
    char compiler[64];     /* версия компилятора */
    int  cores;            /* число физических ядер */
    int  threads;          /* число логических потоков */
    double freq_max_mhz;   /* максимальная тактовая частота, МГц */
} sysinfo_t;

/* Заполнение структуры сведениями о текущей системе. */
void sysinfo_collect(sysinfo_t *info);

/* Привязка процесса к одному логическому ядру. Применяется при измерении
   однопоточных методов: исключает перенос потока планировщиком между
   ядрами и связанную с этим потерю содержимого кэш-памяти. */
int cpu_pin(int cpu);

/* Снятие привязки: процессу вновь доступны все логические ядра.
   Необходимо перед измерением многопоточного режима. */
int cpu_unpin(void);

/* Число логических ядер, доступных процессу в текущий момент. */
int cpu_available(void);

#endif /* SYSINFO_H */

/* timer.h - высокоточное измерение интервалов времени */
#ifndef TIMER_H
#define TIMER_H

/* Текущее значение монотонных часов в секундах.
   Используется CLOCK_MONOTONIC_RAW: часы не корректируются службой
   синхронизации времени и не зависят от изменения тактовой частоты. */
double timer_now(void);

/* Разрешение используемого источника времени, с. */
double timer_resolution(void);

#endif /* TIMER_H */

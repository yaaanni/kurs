/* fib.h - алгоритмы вычисления чисел Фибоначчи */
#ifndef FIB_H
#define FIB_H

#include <stdint.h>
#include <stddef.h>

/* ---- методы, работающие в 64-разрядных регистрах (n <= 93) ---- */

/* Наивный рекурсивный метод, сложность O(2^n).
   Создаёт нагрузку на стек вызовов и блок предсказания переходов. */
uint64_t fib_recursive(int n);

/* Итерационный метод, сложность O(n).
   Создаёт зависимую цепочку целочисленных сложений в АЛУ. */
uint64_t fib_iterative(int n);

/* Итерационный метод, повторённый repeats раз.
   Повторение необходимо, чтобы длительность одного измерения
   существенно превышала разрешение таймера. */
uint64_t fib_iterative_repeat(int n, long repeats);

/* Метод динамического программирования (мемоизация).
   table - массив не менее чем из n + 1 элементов. */
uint64_t fib_memo(int n, uint64_t *table);

/* ---- длинная арифметика (n не ограничено разрядностью регистра) ---- */

/* Целое число произвольной длины: массив 64-разрядных «цифр». */
typedef struct {
    uint64_t *limb;   /* младшая «цифра» хранится первой */
    size_t    len;    /* число значащих «цифр» */
    size_t    cap;    /* ёмкость массива */
} bignum_t;

int  bignum_init(bignum_t *x, size_t cap);
void bignum_free(bignum_t *x);

/* Вычисление n-го числа Фибоначчи в длинной арифметике.
   Рабочий набор растёт пропорционально n, что создаёт нагрузку
   на подсистему кэш-памяти. Возвращает число значащих «цифр» результата. */
size_t fib_bignum(long n, bignum_t *a, bignum_t *b, bignum_t *c);

/* ---- многопоточный режим ---- */

/* Параллельное вычисление tasks независимых значений fib_recursive(n)
   в threads потоках. Возвращает контрольную сумму результатов. */
uint64_t fib_parallel(int n, int tasks, int threads);

#endif /* FIB_H */

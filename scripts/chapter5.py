    if not both:
        return

    # сравнительные выводы формируются только при наличии обеих систем
    ratios = {}
    for m in ('recursive', 'iterative', 'bignum'):
        i = data[m]['intel']
        a = data[m]['amd']
        common = sorted(set(i) & set(a))
        if common:
            p = common[-1]
            ratios[m] = i[p]['median'] / a[p]['median']
    pi = data['parallel']['intel']
    pa = data['parallel']['amd']
    if pi and pa:
        ratios['parallel'] = min(v['median'] for v in pi.values()) / \
                             min(v['median'] for v in pa.values())

    names = {'recursive': 'наивном рекурсивном методе',
             'iterative': 'итерационном методе',
             'bignum': 'методе длинной арифметики',
             'parallel': 'многопоточном режиме'}

    def phrase(r):
        """Описание отношения времён выполнения без предположения о том,
        какая из систем оказалась быстрее."""
        if r > 1.02:
            return 'быстрее в %s' % times(r)
        if r < 0.98:
            return 'медленнее в %s' % times(1.0 / r)
        return 'практически одинаково'

    parts = ['на %s \u2014 %s' % (names[m], phrase(r)) for m, r in ratios.items()]
    faster = sum(1 for r in ratios.values() if r > 1.02)
    if faster == len(ratios):
        lead = ('процессор AMD Ryzen 7 7840HS превосходит процессор '
                'Intel Core i7-8565U по всем реализованным методам')
    elif faster == 0:
        lead = ('процессор AMD Ryzen 7 7840HS не превосходит процессор '
                'Intel Core i7-8565U ни по одному из реализованных методов')
    else:
        lead = ('соотношение быстродействия процессоров AMD Ryzen 7 7840HS и '
                'Intel Core i7-8565U различается по методам вычисления')

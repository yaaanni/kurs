import csv
import os
import re
from collections import defaultdict

CPU_FULL = {'intel': 'Intel Core i7-8565U', 'amd': 'AMD Ryzen 7 7840HS'}


def load(results_dir):
    data = defaultdict(lambda: defaultdict(dict))
    for name in sorted(os.listdir(results_dir)):
        if not name.endswith('.csv'):
            continue
        with open(os.path.join(results_dir, name), newline='', encoding='utf-8') as f:
            for r in csv.DictReader(f):
                data[r['method']][r['cpu']][float(r['param'])] = {
                    'median': float(r['median_s']),
                    'min': float(r['min_s']),
                    'sd': float(r['stddev_s']),
                    'runs': int(r['runs']),
                    'extra': float(r['extra']),
                }
    return data


def read_log(results_dir, label):
    """Извлечение условий эксперимента из протокола прогона."""
    path = os.path.join(results_dir, '%s.log' % label)
    info = {}
    if not os.path.exists(path):
        return info
    txt = open(path, encoding='utf-8').read()
    pat = {
        'governor': r'governor:\s*(\S+)',
        'driver': r'драйвер частоты:\s*(\S+)',
        'freq_avg': r'средняя\s+(\d+)\s*МГц',
        'freq_max': r'максимальная\s+(\d+)\s*МГц',
        'cpu': r'Процессор\s*\.+\s*(.+)',
        'os': r'Операционная система\s*\.+\s*(.+)',
        'kernel': r'Версия ядра\s*\.+\s*(.+)',
        'gcc': r'Компилятор\s*\.+\s*(.+)',
        'cores': r'Ядер / потоков\s*\.+\s*(.+)',
        'runs': r'(\d+)\s+учитываемых прогонов',
        'warmup': r'Серия:\s*(\d+)\s+прогонов прогрева',
    }
    for k, p in pat.items():
        m = re.search(p, txt)
        if m:
            info[k] = m.group(1).strip()
    return info


def fmt(x, nd=3):
    return ('%.*f' % (nd, x)).replace('.', ',')


def grp(x):
    """Разбиение больших чисел на разряды неразрывным пробелом."""
    s = '%d' % int(round(x))
    out = ''
    while len(s) > 3:
        out = '\u00a0' + s[-3:] + out
        s = s[:-3]
    return s + out


def times(x, nd=2):
    """Значение с согласованным словом «раз» или «раза»."""
    v = fmt(x, nd)
    if nd == 0:
        k = int(round(x))
        if k % 10 == 1 and k % 100 != 11:
            w = 'раз'
        elif k % 10 in (2, 3, 4) and k % 100 not in (12, 13, 14):
            w = 'раза'
        else:
            w = 'раз'
        return '%s %s' % (grp(k), w)
    return '%s раза' % v


class Num:
    """Сквозная нумерация таблиц и рисунков в пределах раздела."""

    def __init__(self, section):
        self.section = section
        self.t = 0
        self.f = 0

    def table(self):
        self.t += 1
        return '%d.%d' % (self.section, self.t)

    def fig(self):
        self.f += 1
        return '%d.%d' % (self.section, self.f)


